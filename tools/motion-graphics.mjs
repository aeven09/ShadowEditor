#!/usr/bin/env node
import {
  copyFileSync, cpSync, existsSync, mkdirSync, readFileSync, writeFileSync
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const PROJECT_PATH = join(ROOT, "motion-graphics", "project.json");
export const KIT_ROOT = join(ROOT, "kit");
export const OUTPUT_DIR = join(KIT_ROOT, "video-projects", "shadoweditor-documentary-headline");
const STARTER_DIR = join(KIT_ROOT, "examples", "starter");
const GSAP_DIST = join(KIT_ROOT, "node_modules", "gsap", "dist", "gsap.min.js");
const TOKEN_SOURCE = join(ROOT, "motion-graphics", "styles", "documentary-red", "tokens.css");
const DESIGN_SOURCE = join(ROOT, "motion-graphics", "styles", "documentary-red", "DESIGN.md");
export const GENERATED_MARKER = "<!-- Generated by ShadowEditor documentary-motion MVP. Edit motion-graphics/project.json, then rebuild. -->";

const ID_RE = /^[a-z0-9][a-z0-9_-]{0,63}$/;
const HEX_RE = /^#[0-9a-fA-F]{6}$/;
const ENTER_PRESETS = new Set(["none", "slide-up", "fade", "scale-in"]);
const EXIT_PRESETS = new Set(["none", "fade", "slide-down"]);
const EASES = new Set(["none", "power2.out", "power3.out", "back.out(1.4)", "power2.inOut"]);
const KEY_PROPS = new Set(["offsetX", "offsetY", "scale", "opacity"]);
const KEY_EASES = new Set(["none", "power1.in", "power1.out", "power2.inOut", "power3.out", "back.out(1.4)"]);

const isObject = value => value !== null && typeof value === "object" && !Array.isArray(value);
const isFiniteNumber = value => typeof value === "number" && Number.isFinite(value);
function range(errors, label, value, min, max) {
  if (!isFiniteNumber(value) || value < min || value > max) errors.push(label + " must be a finite number from " + min + " to " + max + ".");
}
function stringField(errors, label, value, max, required = false) {
  if (typeof value !== "string") errors.push(label + " must be a string.");
  else {
    if (value.length > max) errors.push(label + " cannot exceed " + max + " characters.");
    if (required && !value.trim()) errors.push(label + " cannot be empty.");
  }
}
export function validateProject(project) {
  const errors = [];
  if (!isObject(project)) return ["Project must be a JSON object."];
  if (project.version !== 1) errors.push("version must equal 1.");
  if (!isObject(project.canvas)) errors.push("canvas must be an object.");
  else {
    for (const [name, min, max] of [["width", 320, 7680], ["height", 320, 4320], ["fps", 1, 120]]) {
      const value = project.canvas[name];
      if (!Number.isInteger(value) || value < min || value > max) errors.push("canvas." + name + " must be an integer from " + min + " to " + max + ".");
    }
  }
  if (!Array.isArray(project.scenes) || project.scenes.length < 1 || project.scenes.length > 60) {
    errors.push("scenes must contain between 1 and 60 scenes.");
    return errors;
  }
  const ids = new Set();
  project.scenes.forEach((scene, index) => {
    const label = "scenes[" + index + "]";
    if (!isObject(scene)) { errors.push(label + " must be an object."); return; }
    if (typeof scene.id !== "string" || !ID_RE.test(scene.id)) errors.push(label + ".id must be a safe lowercase slug.");
    else if (ids.has(scene.id)) errors.push(label + ".id must be unique.");
    else ids.add(scene.id);
    if (scene.type !== "headline") errors.push(label + ".type must be headline in this MVP.");
    range(errors, label + ".start", scene.start, 0, 86400);
    range(errors, label + ".duration", scene.duration, 0.051, 300);
    if (!isObject(scene.props)) errors.push(label + ".props must be an object.");
    else {
      const p = scene.props;
      stringField(errors, label + ".props.eyebrow", p.eyebrow, 100);
      stringField(errors, label + ".props.headline", p.headline, 180, true);
      stringField(errors, label + ".props.highlight", p.highlight, 180);
      stringField(errors, label + ".props.subheadline", p.subheadline, 220);
      if (typeof p.accentColor !== "string" || !HEX_RE.test(p.accentColor)) errors.push(label + ".props.accentColor must be a six-digit hex color.");
      range(errors, label + ".props.fontSize", p.fontSize, 18, 300);
      range(errors, label + ".props.x", p.x, 0, isObject(project.canvas) && isFiniteNumber(project.canvas.width) ? project.canvas.width : 7680);
      range(errors, label + ".props.y", p.y, 0, isObject(project.canvas) && isFiniteNumber(project.canvas.height) ? project.canvas.height : 4320);
      range(errors, label + ".props.maxWidth", p.maxWidth, 160, isObject(project.canvas) && isFiniteNumber(project.canvas.width) ? project.canvas.width : 7680);
      if (typeof p.showPanel !== "boolean") errors.push(label + ".props.showPanel must be boolean.");
      range(errors, label + ".props.panelOpacity", p.panelOpacity, 0, 0.9);
    }
    if (!isObject(scene.animation)) { errors.push(label + ".animation must be an object."); return; }
    const a = scene.animation;
    if (!isObject(a.enter)) errors.push(label + ".animation.enter must be an object.");
    else {
      if (!ENTER_PRESETS.has(a.enter.preset)) errors.push(label + " has an unsupported entrance preset.");
      range(errors, label + ".animation.enter.duration", a.enter.duration, 0, 5);
      if (!EASES.has(a.enter.ease)) errors.push(label + " has an unsupported entrance ease.");
    }
    if (!isObject(a.exit)) errors.push(label + ".animation.exit must be an object.");
    else {
      if (!EXIT_PRESETS.has(a.exit.preset)) errors.push(label + " has an unsupported exit preset.");
      range(errors, label + ".animation.exit.duration", a.exit.duration, 0, 5);
    }
    if (!Array.isArray(a.keyframes)) errors.push(label + ".animation.keyframes must be an array.");
    else {
      if (a.keyframes.length > 200) errors.push(label + " cannot have more than 200 keyframes.");
      const pairs = new Set();
      a.keyframes.forEach((frame, i) => {
        const keyLabel = label + ".animation.keyframes[" + i + "]";
        if (!isObject(frame)) { errors.push(keyLabel + " must be an object."); return; }
        range(errors, keyLabel + ".time", frame.time, 0, isFiniteNumber(scene.duration) ? scene.duration : 300);
        if (!KEY_PROPS.has(frame.property)) errors.push(keyLabel + ".property is unsupported.");
        if (frame.ease !== undefined && !KEY_EASES.has(frame.ease)) errors.push(keyLabel + ".ease is unsupported.");
        range(errors, keyLabel + ".value", frame.value, -4000, 4000);
        if (frame.property === "scale" && isFiniteNumber(frame.value) && (frame.value < 0.01 || frame.value > 10)) errors.push(keyLabel + ".scale must be between 0.01 and 10.");
        if (frame.property === "opacity" && isFiniteNumber(frame.value) && (frame.value < 0 || frame.value > 1)) errors.push(keyLabel + ".opacity must be between 0 and 1.");
        const pair = String(frame.property) + "@" + String(frame.time);
        if (pairs.has(pair)) errors.push(keyLabel + " duplicates a property/time keyframe.");
        pairs.add(pair);
      });
    }
    if (isFiniteNumber(scene.duration)) {
      if (isObject(a.enter) && isFiniteNumber(a.enter.duration) && a.enter.duration > scene.duration) errors.push(label + " entrance duration cannot exceed scene duration.");
      if (isObject(a.exit) && isFiniteNumber(a.exit.duration) && a.exit.duration > scene.duration) errors.push(label + " exit duration cannot exceed scene duration.");
    }
  });
  return errors;
}
export function readProject(path = PROJECT_PATH) { return JSON.parse(readFileSync(path, "utf8")); }
export function htmlEscape(value) {
  return String(value).replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;").replaceAll("'", "&#39;");
}
function linesHtml(value) { return htmlEscape(value).replaceAll("\n", "<br>"); }
function headlineHtml(text, highlight) {
  const source = String(text);
  const phrase = String(highlight || "");
  const at = phrase ? source.toLowerCase().indexOf(phrase.toLowerCase()) : -1;
  if (at < 0) return linesHtml(source);
  return linesHtml(source.slice(0, at)) + '<span class="doc-highlight">' + linesHtml(source.slice(at, at + phrase.length)) + "</span>" + linesHtml(source.slice(at + phrase.length));
}
function num(value) {
  if (!isFiniteNumber(value)) throw new TypeError("Expected a finite number during composition generation.");
  return String(Math.round(value * 1000) / 1000);
}
function cardMarkup(scene, index) {
  const p = scene.props;
  return [
    '<div id="scene-' + scene.id + '" class="scene-clip clip" data-start="' + num(scene.start) + '" data-duration="' + num(scene.duration) + '" data-track-index="' + (index + 1) + '">',
    '<div class="scene-content" style="--doc-x:' + num(p.x) + 'px;--doc-y:' + num(p.y) + 'px;--doc-max-width:' + num(p.maxWidth) + 'px;--doc-font-size:' + num(p.fontSize) + 'px;--doc-accent:' + p.accentColor + ';--doc-panel-opacity:' + num(p.showPanel ? p.panelOpacity : 0) + '">',
    '<div class="doc-card"><div class="doc-card-motion">',
    p.eyebrow ? '<div class="doc-eyebrow" data-slot="eyebrow">' + linesHtml(p.eyebrow) + "</div>" : "",
    '<div class="doc-rule"></div>',
    '<h1 class="doc-headline" data-slot="headline">' + headlineHtml(p.headline, p.highlight) + "</h1>",
    p.subheadline ? '<p class="doc-subheadline" data-slot="subheadline">' + linesHtml(p.subheadline) + "</p>" : "",
    "</div></div></div></div>"
  ].join("\n");
}
export function renderComposition(project) {
  const errors = validateProject(project);
  if (errors.length) throw new Error("Project validation failed:\n- " + errors.join("\n- "));
  const { width, height, fps } = project.canvas;
  const duration = Math.max(...project.scenes.map(scene => scene.start + scene.duration));
  const compositionId = "shadoweditor-documentary-headline";
  const html = [
    "<!doctype html>",
    '<html lang="en"><head><meta charset="utf-8"><title>ShadowEditor Documentary Headline</title>',
    GENERATED_MARKER,
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<link rel="stylesheet" href="motion.css"></head><body>',
    '<div id="root" class="doc-stage" data-composition-id="' + compositionId + '" data-start="0" data-duration="' + num(duration) + '" data-width="' + width + '" data-height="' + height + '" data-fps="' + fps + '">',
    '<div id="doc-ambient" class="doc-ambient clip" data-start="0" data-duration="' + num(duration) + '" data-track-index="0"></div>',
    project.scenes.map(cardMarkup).join("\n"),
    "</div>",
    '<script src="assets/gsap.min.js"></script>',
    "<script>",
    "const tl = gsap.timeline({ paused: true });"
  ];
  for (const scene of project.scenes) {
    const target = "#scene-" + scene.id + " .doc-card";
    const motionTarget = "#scene-" + scene.id + " .doc-card-motion";
    const enter = scene.animation.enter;
    const exit = scene.animation.exit;
    if (enter.preset !== "none" && enter.duration > 0) {
      const from = { autoAlpha: 0 };
      const to = { autoAlpha: 1, duration: enter.duration, ease: enter.ease };
      if (enter.preset === "slide-up") from.y = 38;
      if (enter.preset === "scale-in") from.scale = 0.94;
      to.y = 0;
      to.scale = 1;
      html.push("tl.fromTo(" + JSON.stringify(target) + ", " + JSON.stringify(from) + ", " + JSON.stringify(to) + ", " + num(scene.start) + ");");
    }
    const byProperty = new Map();
    scene.animation.keyframes.slice().sort((a, b) => a.time - b.time || String(a.property).localeCompare(String(b.property))).forEach(frame => {
      if (!byProperty.has(frame.property)) byProperty.set(frame.property, []);
      byProperty.get(frame.property).push(frame);
    });
    for (const [property, frames] of byProperty.entries()) {
      const gsapProperty = property === "offsetX" ? "x" : property === "offsetY" ? "y" : property;
      let previousTime = 0;
      for (const frame of frames) {
        const tweenTime = scene.start + previousTime;
        const delta = frame.time - previousTime;
        if (delta <= 0) html.push("tl.set(" + JSON.stringify(motionTarget) + ", {" + gsapProperty + ":" + num(frame.value) + "}, " + num(scene.start + frame.time) + ");");
        else html.push("tl.to(" + JSON.stringify(motionTarget) + ", {" + gsapProperty + ":" + num(frame.value) + ",duration:" + num(delta) + ",ease:" + JSON.stringify(frame.ease || "none") + "}, " + num(tweenTime) + ");");
        previousTime = frame.time;
      }
    }
    if (exit.preset !== "none" && exit.duration > 0) {
      const vars = { autoAlpha: 0, duration: exit.duration, ease: "power2.in" };
      if (exit.preset === "slide-down") vars.y = 28;
      html.push("tl.to(" + JSON.stringify(target) + ", " + JSON.stringify(vars) + ", " + num(scene.start + scene.duration - exit.duration) + ");");
    }
  }
  html.push("tl.to({}, { duration: " + num(duration) + " }, 0);");
  html.push("window.__timelines = window.__timelines || {};");
  html.push("window.__timelines[" + JSON.stringify(compositionId) + "] = tl;");
  html.push("</script></body></html>");
  const css = [
    '@import url("styles/tokens.css");',
    "* { box-sizing: border-box; }",
    "html,body { margin:0; width:" + width + "px; height:" + height + "px; overflow:hidden; background:transparent; color:var(--doc-ink); font-family:var(--doc-font); }",
    "#root { position:relative; width:" + width + "px; height:" + height + "px; overflow:hidden; isolation:isolate; background:radial-gradient(ellipse at 76% 18%,rgba(var(--doc-red-rgb),.13),transparent 45%),var(--doc-bg); }",
    ".doc-ambient { position:absolute; inset:0; opacity:.42; background-image:linear-gradient(rgba(var(--doc-ink-rgb),.06) 1px,transparent 1px),linear-gradient(90deg,rgba(var(--doc-ink-rgb),.06) 1px,transparent 1px); background-size:80px 80px; }",
    ".doc-ambient:after { content:''; position:absolute; width:520px; height:520px; right:-140px; top:-220px; border:1px solid rgba(var(--doc-red-rgb),.28); border-radius:50%; box-shadow:0 0 0 44px rgba(229,43,50,.025),0 0 0 88px rgba(229,43,50,.02); }",
    ".scene-clip { position:absolute; inset:0; width:100%; height:100%; overflow:hidden; }",
    ".scene-content { display:flex; flex-direction:column; width:100%; height:100%; padding:var(--doc-y) max(0px,calc(100% - var(--doc-x) - var(--doc-max-width))) 0 var(--doc-x); gap:0; }",
    ".doc-card { position:relative; width:100%; max-width:var(--doc-max-width); min-width:0; color:var(--doc-ink); isolation:isolate; }",
    ".doc-card:before { content:''; position:absolute; z-index:-1; inset:-30px -32px -28px; border-left:6px solid var(--doc-accent); background:rgba(var(--doc-panel-rgb),var(--doc-panel-opacity)); box-shadow:0 22px 75px rgba(0,0,0,.28); }",
    ".doc-card-motion { position:relative; transform-origin:left top; will-change:transform,opacity; }",
    ".doc-eyebrow { margin:0 0 18px; color:var(--doc-yellow); font:800 24px/1.15 var(--doc-label-font); letter-spacing:.2em; text-transform:uppercase; }",
    ".doc-rule { width:96px; height:6px; background:var(--doc-accent); margin:0 0 18px; }",
    ".doc-headline { margin:0; max-width:100%; color:var(--doc-ink); font-size:var(--doc-font-size); font-weight:900; line-height:.96; letter-spacing:-.035em; text-transform:uppercase; overflow-wrap:anywhere; }",
    ".doc-highlight { color:var(--doc-accent); }",
    ".doc-subheadline { margin:24px 0 0; color:var(--doc-muted); font-size:28px; font-weight:500; line-height:1.3; max-width:100%; }"
  ].join("\n") + "\n";
  return { html: html.join("\n"), css, duration };
}
export function buildProject(project = readProject()) {
  const errors = validateProject(project);
  if (errors.length) throw new Error("Project validation failed:\n- " + errors.join("\n- "));
  if (!existsSync(STARTER_DIR)) throw new Error("Herk Edit Kit is not installed. Run node setup.mjs from the ShadowEditor root first.");
  if (!existsSync(GSAP_DIST)) throw new Error("GSAP is missing from kit/node_modules. Run node setup.mjs again.");
  const indexPath = join(OUTPUT_DIR, "index.html");
  if (existsSync(OUTPUT_DIR) && (!existsSync(indexPath) || !readFileSync(indexPath, "utf8").includes(GENERATED_MARKER))) {
    throw new Error("Refusing to overwrite an existing non-generated project at " + OUTPUT_DIR);
  }
  if (!existsSync(OUTPUT_DIR)) {
    mkdirSync(dirname(OUTPUT_DIR), { recursive: true });
    cpSync(STARTER_DIR, OUTPUT_DIR, { recursive: true });
  }
  for (const folder of ["assets", "renders", "compositions", "styles"]) mkdirSync(join(OUTPUT_DIR, folder), { recursive: true });
  copyFileSync(GSAP_DIST, join(OUTPUT_DIR, "assets", "gsap.min.js"));
  const generated = renderComposition(project);
  writeFileSync(indexPath, generated.html, "utf8");
  writeFileSync(join(OUTPUT_DIR, "motion.css"), generated.css, "utf8");
  writeFileSync(join(OUTPUT_DIR, "styles", "tokens.css"), readFileSync(TOKEN_SOURCE, "utf8"), "utf8");
  writeFileSync(join(OUTPUT_DIR, "DESIGN.md"), readFileSync(DESIGN_SOURCE, "utf8"), "utf8");
  const metaPath = join(OUTPUT_DIR, "meta.json");
  let meta = {};
  if (existsSync(metaPath)) {
    try { meta = JSON.parse(readFileSync(metaPath, "utf8")); } catch { meta = {}; }
  }
  meta.name = "shadoweditor-documentary-headline";
  meta.title = "ShadowEditor Documentary Headline";
  writeFileSync(metaPath, JSON.stringify(meta, null, 2) + "\n", "utf8");
  return { outputDir: OUTPUT_DIR, indexPath, duration: generated.duration, sceneCount: project.scenes.length };
}
function main() {
  const command = process.argv[2] || "help";
  if (command === "help" || command === "--help") {
    console.log("ShadowEditor documentary motion graphics\n\nCommands:\n  node tools/motion-graphics.mjs validate\n  node tools/motion-graphics.mjs build");
    return;
  }
  let project;
  try { project = readProject(); } catch (error) {
    console.error("Unable to read project configuration: " + error.message);
    process.exitCode = 1;
    return;
  }
  if (command === "validate") {
    const errors = validateProject(project);
    if (errors.length) {
      console.error("Project validation failed:\n- " + errors.join("\n- "));
      process.exitCode = 1;
    } else {
      const duration = Math.max(...project.scenes.map(scene => scene.start + scene.duration));
      console.log("Project is valid: " + project.scenes.length + " scene(s), " + duration.toFixed(2) + " seconds.");
    }
    return;
  }
  if (command === "build") {
    try {
      const result = buildProject(project);
      console.log("Generated " + result.outputDir);
      console.log("Scenes: " + result.sceneCount + "; duration: " + result.duration.toFixed(2) + " seconds.");
      console.log("Next: cd kit/video-projects/shadoweditor-documentary-headline");
      console.log("Run npx hyperframes lint, node ../../scripts/preflight.mjs ., then npx hyperframes preview.");
    } catch (error) {
      console.error("Build failed: " + error.message);
      process.exitCode = 1;
    }
    return;
  }
  console.error("Unknown command: " + command);
  process.exitCode = 2;
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
